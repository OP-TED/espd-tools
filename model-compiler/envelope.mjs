// The compiled-model envelope (model/compiled-model.json): version + provenance +
// inventory of the published model. Deterministic by construction: no timestamps,
// stable ordering, and content hashes over line-ending-normalised text so a Windows
// checkout and a Linux CI run of the same sources produce the same bytes.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import Ajv from 'ajv';
import { compareCodePoint } from './order.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
export const schemaPath = path.join(here, 'schema', 'compiled-model.schema.json');

const PART_ORDER = ['I', 'II', 'III', 'IV', 'V', 'VI'];

const lf = (text) => text.replace(/\r\n/g, '\n');
const sha256 = (text) => crypto.createHash('sha256').update(text, 'utf8').digest('hex');

/** SHA-256 of a text file with line endings normalised to LF. */
export function hashFile(file) {
  return sha256(lf(fs.readFileSync(file, 'utf8')));
}

/**
 * SHA-256 over the enrichment sources the compiler consumes: registries/*.json and
 * criteria/*.json and the .json files of each parts/<part> folder (when present), as sorted `relative/path\n<LF-normalised content>\n`.
 */
export function hashEnrichment(enrichmentDir) {
  const files = [];
  for (const sub of ['registries', 'criteria']) {
    const dir = path.join(enrichmentDir, sub);
    for (const f of fs.readdirSync(dir).filter(n => n.endsWith('.json')).sort(compareCodePoint)) files.push(`${sub}/${f}`);
  }
  const partsDir = path.join(enrichmentDir, 'parts');
  if (fs.existsSync(partsDir)) {
    for (const p of fs.readdirSync(partsDir, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort(compareCodePoint)) {
      for (const f of fs.readdirSync(path.join(partsDir, p)).filter(n => n.endsWith('.json')).sort(compareCodePoint)) files.push(`parts/${p}/${f}`);
    }
  }
  const h = crypto.createHash('sha256');
  for (const rel of files) {
    h.update(rel + '\n', 'utf8');
    h.update(lf(fs.readFileSync(path.join(enrichmentDir, rel), 'utf8')) + '\n', 'utf8');
  }
  return { sha256: h.digest('hex'), files: files.length };
}

/** ESPD and UBL versions from the codelists.json that accompanies the code lists. */
export function readVersions(codelistsDir) {
  const file = path.join(codelistsDir, 'codelists.json');
  if (!fs.existsSync(file)) {
    throw new Error(`codelists.json not found in ${codelistsDir}; it carries espdVersion/ublVersion`);
  }
  const { espdVersion, ublVersion } = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!espdVersion || !ublVersion) throw new Error(`${file} lacks espdVersion and/or ublVersion`);
  return { espdVersion, ublVersion };
}

/**
 * Build the envelope.
 * @param {object} p
 * @param {string} p.espdVersion
 * @param {string} p.ublVersion
 * @param {object} p.provenance  everything under `provenance` (generator, structure, enrichment, valueTypeSource, sourceRef?)
 * @param {object[]} p.entries   one per criterion: { key, id, code, tag?, part, leaves, repeatableBindings, valueTypes[], files{} }
 * @param {object} p.valueTypeRegistry  the value-types registry ({ valueTypes: { NAME: { requestXml?, responseXml? } } })
 * @param {string[]} p.registries  published registry paths
 * @param {object[]} p.parts  the administrative parts: { part, manifest, sections: [{ id, schema, example, mapping, form }] }
 */
export function buildEnvelope({ espdVersion, ublVersion, provenance, entries, valueTypeRegistry, registries, parts }) {
  const criteria = [...entries]
    .map(e => ({ ...e, valueTypes: [...e.valueTypes].sort(compareCodePoint) }))
    .sort((a, b) => PART_ORDER.indexOf(a.part) - PART_ORDER.indexOf(b.part) || compareCodePoint(a.key, b.key));

  const usage = new Map();
  for (const c of criteria) for (const t of c.valueTypes) usage.set(t, (usage.get(t) ?? 0) + 1);
  const valueTypes = Object.keys(valueTypeRegistry.valueTypes).sort(compareCodePoint).map(name => {
    const def = valueTypeRegistry.valueTypes[name];
    return { name, request: !!def.requestXml, response: !!def.responseXml, usedBy: usage.get(name) ?? 0 };
  });

  const orderedParts = [...parts].sort((a, b) => PART_ORDER.indexOf(a.part) - PART_ORDER.indexOf(b.part));

  return {
    $comment: 'GENERATED by espd-tools/model-compiler. Do not hand-edit; regenerate. The manifest of the published ESPD model: version, provenance, and an inventory of criteria and value types with their files. See README.md in this folder.',
    envelopeVersion: 1,
    espdVersion,
    ublVersion,
    provenance,
    counts: {
      criteria: criteria.length,
      valueTypes: valueTypes.length,
      instanceDataFiles: criteria.length * 2,
      xmlMappingFiles: criteria.length * 2,
      compiledFiles: criteria.length,
      partSections: orderedParts.reduce((n, p) => n + p.sections.length, 0),
    },
    criteria,
    valueTypes,
    parts: orderedParts,
    registries: [...registries].sort(compareCodePoint),
  };
}

/** Validate an envelope against the schema. Returns the list of problems (empty = valid). */
export function validateEnvelope(envelope) {
  const ajv = new Ajv({ allErrors: true, strict: true });
  const validate = ajv.compile(JSON.parse(fs.readFileSync(schemaPath, 'utf8')));
  if (validate(envelope)) return [];
  return validate.errors.map(e => `${e.instancePath || '/'} ${e.message}${e.params?.additionalProperty ? ` ("${e.params.additionalProperty}")` : ''}`);
}
